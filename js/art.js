export const spriteFor = (name) => {
  name = String(name || '');
  if (name.startsWith('badge-')) { const id = name.slice(6); return BADGE_ICON[id] || (id.startsWith('streak-') ? 'sun' : 'star'); }
  return ALIAS[name] || (S[name] ? name : 'leaf');
};
// one <path> of runs per row: crisp at any size
const pathCache = new Map();
function spritePath(key) {
  if (pathCache.has(key)) return pathCache.get(key);
  let d = '';
  (S[key] || S.leaf).forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') { let w = 1; while (row[x + w] === '#') w++; d += `M${x} ${y}h${w}v1h-${w}z`; x += w; } else x++;
    }
  });
  pathCache.set(key, d);
  return d;
}
export const pixelPath = (name) => spritePath(spriteFor(name));

export function art(name, { size = 48, cls = '' } = {}) {
  try {
    name = String(name || '');
    if (name.startsWith('scene-') || name.startsWith('celebrate-')) return '';
    // pixel icons look best on whole multiples of 16; snap to the nearest step of 8 px
    const s = Math.max(8, Math.round(size / 8) * 8);
    return `<svg class="art pxi ${cls}" width="${s}" height="${s}" viewBox="0 0 16 16" fill="currentColor" stroke="none" shape-rendering="crispEdges" aria-hidden="true" focusable="false" data-art="${name}"><path d="${pixelPath(name)}"/></svg>`;
  } catch { return ''; }
}

